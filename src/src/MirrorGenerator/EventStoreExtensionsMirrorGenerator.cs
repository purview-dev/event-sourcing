using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Purview.EventSourcing.MirrorGenerator;

/// <summary>
/// Mirrors the <c>IEventStoreCore&lt;T&gt;</c> convenience extensions onto the non-generic
/// <c>IEventStore</c> facade.
/// </summary>
/// <remarks>
/// The two sets were hand-maintained copies of each other, which is a standing invitation to drift. Only
/// the receiver and the type argument differ, so the facade set is derived from the typed one and the
/// facade keeps a hand-written partial for the members that have no typed counterpart.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class EventStoreExtensionsMirrorGenerator : IIncrementalGenerator
{
	const string SourceClass = "IEventStoreCoreExtensions";
	const string TargetClass = "IEventStoreExtensions";
	const string TypedReceiver = "IEventStoreCore<T>";
	const string FacadeReceiver = "IEventStore";

	/// <inheritdoc/>
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		// The transform produces the finished source text, so the pipeline caches on a string rather
		// than on syntax nodes or a semantic model.
		var mirrored = context
			.SyntaxProvider.CreateSyntaxProvider(
				static (node, _) => node is ClassDeclarationSyntax { Identifier.ValueText: SourceClass },
				static (syntaxContext, cancellationToken) =>
					Mirror((ClassDeclarationSyntax)syntaxContext.Node, syntaxContext.SemanticModel, cancellationToken)
			)
			.Where(static source => source is not null);

		context.RegisterSourceOutput(
			mirrored,
			static (sourceContext, source) =>
				sourceContext.AddSource($"{TargetClass}.g.cs", SourceText.From(source!, Encoding.UTF8))
		);
	}

	static string? Mirror(
		ClassDeclarationSyntax declaration,
		SemanticModel semanticModel,
		CancellationToken cancellationToken
	)
	{
		var members = declaration
			.Members.OfType<MethodDeclarationSyntax>()
			.Where(static method =>
				method.Modifiers.Any(SyntaxKind.PublicKeyword) && method.Modifiers.Any(SyntaxKind.StaticKeyword)
			)
			.Where(method => IsTypedReceiver(method))
			.Select(method => Rewrite(method, semanticModel, cancellationToken))
			.ToArray();

		if (members.Length == 0)
			return null;

		StringBuilder builder = new();
		builder
			.AppendLine("// <auto-generated/>")
			.AppendLine("#nullable enable")
			.AppendLine()
			.AppendLine("using System.Diagnostics.CodeAnalysis;")
			.AppendLine("using Purview.EventSourcing.Aggregates;")
			.AppendLine("using Purview.EventSourcing.Failures;")
			.AppendLine("using Purview.Results;")
			.AppendLine()
			.AppendLine("namespace Purview.EventSourcing;")
			.AppendLine()
			.AppendLine($"static partial class {TargetClass}")
			.AppendLine("{");

		foreach (var member in members)
			builder.AppendLine(member).AppendLine();

		builder.AppendLine("}");

		return builder.ToString();
	}

	static bool IsTypedReceiver(MethodDeclarationSyntax method)
	{
		var receiver = method.ParameterList.Parameters.FirstOrDefault();

		return receiver?.Modifiers.Any(SyntaxKind.ThisKeyword) == true && receiver.Type?.ToString() == TypedReceiver;
	}

	static string Rewrite(
		MethodDeclarationSyntax method,
		SemanticModel semanticModel,
		CancellationToken cancellationToken
	)
	{
		MirrorRewriter rewriter = new(semanticModel, cancellationToken);
		var rewritten = (MethodDeclarationSyntax)rewriter.Visit(method);

		return rewritten.NormalizeWhitespace("\t", "\n").ToFullString();
	}

	sealed class MirrorRewriter(SemanticModel semanticModel, CancellationToken cancellationToken) : CSharpSyntaxRewriter
	{
		public override SyntaxNode? VisitParameter(ParameterSyntax node)
		{
			var visited = (ParameterSyntax)base.VisitParameter(node)!;

			return visited.Type?.ToString() == TypedReceiver
				? visited.WithType(SyntaxFactory.ParseTypeName(FacadeReceiver))
				: visited;
		}

		public override SyntaxNode? VisitInvocationExpression(InvocationExpressionSyntax node)
		{
			// On IEventStoreCore<T> the aggregate type is fixed by the receiver, so a call like
			// DeleteAsync(aggregateId, ...) is unambiguous. On the facade every member is generic, and
			// the interface's own DeleteAsync<T>(T, ...) would win by inferring T from the id. Both the
			// interface members and this class's own extensions therefore need the type argument spelled
			// out, which is decided from the resolved symbol rather than from the method's name.
			var needsTypeArgument =
				node.Expression is MemberAccessExpressionSyntax { Name: IdentifierNameSyntax }
				&& semanticModel.GetSymbolInfo(node, cancellationToken).Symbol is IMethodSymbol symbol
				&& symbol.ContainingType.Name is "IEventStoreCore" or SourceClass;

			var visited = (InvocationExpressionSyntax)base.VisitInvocationExpression(node)!;
			if (!needsTypeArgument || visited.Expression is not MemberAccessExpressionSyntax access)
				return visited;

			var generic = SyntaxFactory.GenericName(
				((IdentifierNameSyntax)access.Name).Identifier,
				SyntaxFactory.TypeArgumentList(
					SyntaxFactory.SingletonSeparatedList<TypeSyntax>(SyntaxFactory.ParseTypeName("T"))
				)
			);

			return visited.WithExpression(access.WithName(generic));
		}

		public override SyntaxTriviaList VisitList(SyntaxTriviaList list) =>
			// The documentation names the receiver too, and a cref to IEventStoreCore{T} would not
			// resolve from a method whose receiver is now IEventStore.
			SyntaxFactory.ParseLeadingTrivia(
				base.VisitList(list).ToFullString().Replace("IEventStoreCore{T}", "IEventStore")
			);
	}
}
